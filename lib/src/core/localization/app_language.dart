import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:shared_preferences/shared_preferences.dart';

enum AppLanguage {
  indonesia('id', 'Indonesia'),
  english('en', 'English');

  final String code;
  final String label;
  const AppLanguage(this.code, this.label);

  static AppLanguage fromLabel(String value) {
    final normalized = value.trim().toLowerCase();
    return AppLanguage.values.firstWhere(
      (lang) =>
          lang.label.toLowerCase() == normalized ||
          lang.code.toLowerCase() == normalized,
      orElse: () => AppLanguage.indonesia);
  }
}

class AppLanguageNotifier extends StateNotifier<AppLanguage> {
  AppLanguageNotifier() : super(AppLanguage.indonesia) {
    _loadLanguage();
  }

  Future<void> _loadLanguage() async {
    final prefs = await SharedPreferences.getInstance();
    final savedLang =
        prefs.getString('language') ?? AppLanguage.indonesia.label;
    state = AppLanguage.fromLabel(savedLang);
  }

  Future<void> setLanguage(String label) async {
    final newLang = AppLanguage.fromLabel(label);
    state = newLang;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('language', newLang.label);
  }

  Future<void> setLanguageByEnum(AppLanguage lang) async {
    state = lang;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('language', lang.label);
  }
}

final appLanguageProvider =
    StateNotifierProvider<AppLanguageNotifier, AppLanguage>((ref) {
  return AppLanguageNotifier();
});

